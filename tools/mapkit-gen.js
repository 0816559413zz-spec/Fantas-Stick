// สร้างคลัง Asset ของ Map Builder (assets/mapkit/kit.json) จากโมเดลที่มีอยู่ในแผนที่ของเกม (assets/maps/*.glb)
// ใช้: node tools/mapkit-gen.js   — รันใหม่เมื่อมีแผนที่ Blender ใหม่/เปลี่ยนชื่อชิ้น. รายการ "user" (Asset ที่ผู้ใช้เพิ่มเองจาก Map Builder) คงเดิมเสมอ
// 1 รายการ = ชิ้น (node) หนึ่งในไฟล์ .glb : Map Builder โหลดไฟล์นั้นแล้วหยิบชิ้นตามชื่อมาวาง ไม่ต้องมีไฟล์โมเดลแยก
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), mapDir = path.join(root, 'assets', 'maps'), outDir = path.join(root, 'assets', 'mapkit');
const SKIP = /^(ground|floor_|env_|anim_|bounds)|_far|mountain|_walls?$|bridge_stones|ford_stone|hoops|teacher|rail_posts|island|tree_edge|drape|_stand|pitch_tower|castle_banners|hall_banners/i;
// [category, match, display name, collides (1), breakable (material), small = no shadow]
const RULES = [
  ['plant', /tuft|flower|mush|drift|web/, 'Small Plant', 0, 0, 1],
  ['plant', /bush/, 'Bush', 0, 0, 1],
  ['tree', /tree|pine/, 'Tree', 1, 'wood', 0],
  ['rock', /rock|boulder|stone|chunk|rubble|crystal/, 'Rock', 1, 'stone', 0],
  ['fence', /fence/, 'Fence', 1, 'wood', 0],
  ['light', /lamp|lantern|torch|brazier|candle|glow/, 'Light', 1, 'stone', 0],
  ['prop', /bench|table|stall|crate|hay|cart|tent|well|log|snowman|hourglass/, 'Prop', 1, 'wood', 0],
  ['build', /column|pillar|statue|obelisk|arch|gargoyle|altar|fallen|windmill|step|wall/, 'Structure', 1, 'stone', 0],
];
const NAME = { tuft: 'Grass Tuft', flower: 'Flowers', mush: 'Mushroom', drift: 'Snow Drift', web: 'Cobweb', bush: 'Bush', tree: 'Tree', pine: 'Pine', rock: 'Rock', boulder: 'Boulder', stone: 'Stone Block', chunk: 'Ice Chunk', rubble: 'Rubble',
  fence: 'Fence', lamp: 'Lamp Post', lantern: 'Lantern', torch: 'Torch', brazier: 'Brazier', candle: 'Candle Stand', glow: 'Glowing Rock', bench: 'Bench', table: 'Long Table', stall: 'Market Stall', crate: 'Crate', hay: 'Hay Pile', tent: 'Tent', well: 'Well',
  log: 'Log', snowman: 'Snowman', hourglass: 'Hourglass', column: 'Column', pillar: 'Pillar', statue: 'Statue', obelisk: 'Obelisk', arch: 'Stone Arch', gargoyle: 'Gargoyle', altar: 'Altar', fallen: 'Fallen Column', windmill: 'Windmill', step: 'Stone Steps', wall: 'Old Wall' };
const MAPN = { valley: 'Valley', castle: 'Castle', forest: 'Forest', hogsmeade: 'Hogsmeade', meadow: 'Meadow', ruins: 'Ruins', lake: 'Lake', greathall: 'Great Hall', pitch: 'Pitch' };
const PER = 3;   // เก็บกี่แบบต่อ 1 ตระกูล (ชิ้นแรก / กลาง / ท้าย — มักต่างขนาด)
const assets = [];
for (const f of fs.readdirSync(mapDir).filter(f => f.endsWith('.glb')).sort()) {
  const mid = f.slice(0, -4), b = fs.readFileSync(path.join(mapDir, f));
  if (fs.existsSync(path.join(root, 'maps', 'build', mid + '.json'))) continue;   // แผนที่ที่ทำจาก Map Builder เอง ไม่นับเป็นคลัง
  const j = JSON.parse(b.slice(20, 20 + b.readUInt32LE(12)).toString());
  const fam = new Map();
  for (const n of j.nodes || []) {
    if (n.mesh == null || !n.name || SKIP.test(n.name)) continue;
    const k = n.name.replace(/([._-]-?\d+)+$/, '');
    if (!fam.has(k)) fam.set(k, []);
    fam.get(k).push(n.name);
  }
  for (const [k, L] of fam) {
    const rule = RULES.find(r => r[1].test(k)); if (!rule) continue;
    const word = (k.match(rule[1]) || [''])[0];
    const pick = L.length <= PER ? L : [L[0], L[L.length >> 1], L[L.length - 1]];
    pick.forEach((node, i) => assets.push({ id: mid + '/' + node, name: (NAME[word] || rule[2]) + (pick.length > 1 ? ' ' + (i + 1) : '') + ' · ' + (MAPN[mid] || mid), cat: rule[0], src: 'maps/' + f, node, col: rule[3], brk: rule[4] || 0, ns: rule[5] }));
  }
}
fs.mkdirSync(outDir, { recursive: true });
const p = path.join(outDir, 'kit.json');
let user = []; try { user = JSON.parse(fs.readFileSync(p, 'utf8')).user || []; } catch (e) {}
const out = { _about: 'Map Builder asset library (mapbuild.html). assets = generated by node tools/mapkit-gen.js from nodes in assets/maps/*.glb • user = assets added with the "Add Asset" button (files in assets/mapkit/). Format: guides/MAP-BUILDER.md',
  v: 1, assets, user };
fs.writeFileSync(p, '{\n "_about": ' + JSON.stringify(out._about) + ',\n "v": 1,\n "assets": [\n  ' + assets.map(a => JSON.stringify(a)).join(',\n  ') + '\n ],\n "user": [\n  ' + user.map(a => JSON.stringify(a)).join(',\n  ') + '\n ]\n}\n');
console.log('OK assets/mapkit/kit.json', assets.length, 'ชิ้น +', user.length, 'ของผู้ใช้');
